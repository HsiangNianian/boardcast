// Actual Preparation component and protocol-shaped metering; never captures host audio.
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
module.exports = async function checkInputPreview(page, baseUrl, evidence='docs/ui-ux-audit-2026-11-03/evidence/implementation') {
  await fs.mkdir(evidence,{recursive:true});
  await page.addInitScript(()=>{
    localStorage.setItem('boardcast.lang','en');
    const qa=window.qa={calls:[],requests:[],startSuccess:true,modelsReady:false,waitStart:false,stopHeld:false};
    let next=0;const callbacks={},listeners={};
    qa.emit=(event,payload)=>callbacks[listeners[event]]?.({event,payload});
    window.__TAURI_EVENT_PLUGIN_INTERNALS__={unregisterListener:event=>delete listeners[event]};
    window.__TAURI_INTERNALS__={transformCallback:f=>{callbacks[++next]=f;return next},unregisterCallback:id=>delete callbacks[id],invoke:async(command,args={})=>{
      qa.calls.push(command);
      if(command==='plugin:event|listen'){listeners[args.event]=args.handler;return args.handler}
      if(command==='voice_status')return {installed:qa.modelsReady,listening:false};
      if(command==='voice_models')return {selection:{provider:'sensevoice',locale:'auto'},senseVoiceInstalled:qa.modelsReady,listening:false,preparing:false,autoLocales:[],apple:null,appleError:null};
      if(command==='voice_devices')return ['Synthetic input'];
      if(command==='voice_input_check_start'){
        qa.requests.push(args);qa.current=args.id;
        qa.emit('voice-input-check',{id:args.id,state:'starting'});
        if(!qa.holdReady)qa.emit('voice-input-check',{id:args.id,state:'active',device:'Synthetic input'});
      }
      if(command==='voice_input_check_stop'){
        qa.stoppedId=args.id;
        if(qa.stopHeld)await new Promise(resolve=>qa.finishStop=resolve);
        qa.emit('voice-input-check',{id:args.id,state:'stopped',reason:'cancelled'});
      }
      return null;
    }};
  });
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(`${baseUrl}/scripts/ui/fixtures/preparation.html`);
  const open=()=>page.getByRole('button',{name:'Open preparation',exact:true}).click();
  const panel=page.getByRole('dialog',{name:'Prepare to start',exact:true});
  const check=panel.getByRole('button',{name:'Check input',exact:true});
  const begin=async()=>{const count=await page.evaluate(()=>window.qa.requests.length);await check.click();await page.waitForFunction(count=>window.qa.requests.length>count,count)};
  await open();await check.waitFor();
  assert.equal(await page.evaluate(()=>window.qa.calls.includes('voice_input_check_start')),false,'opening must not acquire an input');
  assert.equal(await panel.getByRole('button',{name:'Start listening',exact:true}).isDisabled(),true);
  await begin();
  await panel.getByText('Waiting for an input level; no reading yet.',{exact:true}).waitFor();
  assert.equal(await panel.getByRole('meter').count(),0,'unmeasured is not reported as silence');
  const first=await page.evaluate(()=>window.qa.current);
  await page.evaluate(()=>window.qa.emit('voice-input-check',{id:window.qa.current,state:'active',device:'Synthetic input',level:0}));
  await panel.getByRole('meter').waitFor();assert.equal(await panel.getByRole('meter').getAttribute('value'),'0');
  await page.evaluate(()=>window.qa.emit('voice-input-check',{id:window.qa.current,state:'active',device:'Synthetic input',level:0.4}));
  await page.waitForFunction(()=>document.querySelector('meter')?.value===0.4);
  await page.screenshot({path:`${evidence}/input-preview-active.png`,animations:'disabled'});
  await page.setViewportSize({width:720,height:480});
  await panel.getByRole('button',{name:'Stop input check',exact:true}).scrollIntoViewIfNeeded();
  await page.screenshot({path:`${evidence}/input-preview-720.png`,animations:'disabled'});
  const closeBounds=await panel.getByRole('button',{name:'Close',exact:true}).boundingBox();
  assert(closeBounds&&closeBounds.y>=0&&closeBounds.y+closeBounds.height<=480,'close remains visible while checking input');
  await page.setViewportSize({width:1280,height:800});
  assert.equal(await panel.getByRole('combobox',{name:'What to listen to',exact:true}).isDisabled(),true);
  await panel.getByRole('button',{name:'Stop input check',exact:true}).click();
  await check.waitFor();assert.equal(await page.evaluate(()=>window.qa.stoppedId),first);
  await panel.getByRole('combobox',{name:'What to listen to',exact:true}).selectOption('system');
  await begin();
  assert.equal(await page.evaluate(()=>window.qa.requests.at(-1).source),'system');
  await page.evaluate(()=>window.qa.emit('voice-input-check',{id:window.qa.current,state:'error',message:'SYSTEM_AUDIO_PERMISSION'}));
  await panel.getByRole('alert').filter({hasText:'Screen & System Audio Recording'}).waitFor();
  assert.equal(await panel.getByRole('combobox',{name:'What to listen to',exact:true}).inputValue(),'system','permission error must not switch the source');
  await begin();
  await page.evaluate(()=>window.qa.emit('voice-input-check',{id:window.qa.current,state:'stopped',reason:'timeout'}));
  await panel.getByText('The 10-second input check has ended.',{exact:true}).waitFor();
  await page.evaluate(()=>window.qa.emit('voice-input-check',{id:window.qa.current,state:'active',level:0.8}));
  assert.equal(await check.isVisible(),true,'late levels must not reactivate a completed request');
  await begin();
  await page.evaluate(id=>window.qa.emit('voice-input-check',{id,state:'error',message:'stale error'}),first);
  assert.equal(await panel.getByText('stale error',{exact:true}).count(),0);
  await page.evaluate(()=>window.qa.stopHeld=true);
  await panel.getByRole('button',{name:'Close',exact:true}).click();
  await page.waitForFunction(()=>typeof window.qa.finishStop==='function');
  assert.equal(await panel.count(),1,'close waits for native input release');
  await page.evaluate(()=>{window.qa.stopHeld=false;window.qa.finishStop()});
  await panel.waitFor({state:'detached'});
  await open();await begin();
  await panel.getByRole('button',{name:'Type first',exact:true}).click();
  await panel.waitFor({state:'detached'});await page.waitForFunction(()=>window.qa.calls.includes('type'));
  await page.evaluate(()=>{window.qa.modelsReady=true;window.qa.holdReady=true});
  await open();await begin();
  await panel.getByText('Opening the selected input… You can cancel this check.',{exact:true}).waitFor();
  await page.keyboard.press('Escape');await panel.waitFor({state:'detached'});
  await page.evaluate(()=>window.qa.holdReady=false);
  await open();await begin();
  const startsBeforeCancel=await page.evaluate(()=>window.qa.calls.filter(command=>command==='start').length);
  await page.evaluate(()=>{window.qa.stopHeld=true;window.qa.finishStop=null});
  await panel.getByRole('button',{name:'Start listening',exact:true}).click();
  await page.waitForFunction(()=>typeof window.qa.finishStop==='function');
  await panel.getByRole('button',{name:'Cancel starting audio',exact:true}).click();
  await page.waitForFunction(()=>window.qa.calls.includes('cancel'));
  await page.evaluate(()=>{window.qa.stopHeld=false;window.qa.finishStop()});
  await panel.getByRole('button',{name:'Start listening',exact:true}).waitFor();
  assert.equal(await page.evaluate(()=>window.qa.calls.filter(command=>command==='start').length),startsBeforeCancel,'cancel while preview release is pending must prevent recording from starting');
  await begin();
  await panel.getByRole('button',{name:'Start listening',exact:true}).click();
  await panel.waitFor({state:'detached'});
  const calls=await page.evaluate(()=>window.qa.calls);
  assert(calls.lastIndexOf('voice_input_check_stop')<calls.lastIndexOf('start'),'preview must stop before meeting recording');
  assert.equal(calls.some(command=>['voice_start','voice_prepare','voice_select','model_download'].includes(command)),false);
  assert.deepEqual(errors,[]);
  await fs.mkdir(evidence,{recursive:true});
  await fs.writeFile(`${evidence}/input-preview-check.json`,JSON.stringify({passed:true,withoutSpeechModel:true,explicitOnly:true,unknownAndMeasuredSilence:true,staleEventsIgnored:true,closeWaitsForRelease:true,permissionKeepsSource:true,timeout:true,cancelBeforeRecording:true,typingAndRecordingStopPreview:true,pageErrors:errors},null,2));
};
