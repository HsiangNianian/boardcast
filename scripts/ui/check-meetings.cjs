const assert = require('node:assert/strict');
module.exports = async function checkMeetings(page, baseUrl) {
  await page.addInitScript(()=>localStorage.setItem('boardcast.lang','en'));
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(`${baseUrl}/scripts/ui/fixtures/meetings.html`);
  await page.getByRole('button',{name:'Open meetings',exact:true}).click();
  await page.getByRole('alert').waitFor();
  assert.match(await page.getByRole('alert').innerText(),/Injected list failure/);
  await page.evaluate(()=>window.qa.fail='');
  await page.getByRole('button',{name:'Reload list',exact:true}).click();
  await page.evaluate(()=>window.qa.fail='open');
  await page.locator('.meeting-list .open').click();
  await page.getByRole('alert').waitFor();
  assert.match(await page.getByRole('alert').innerText(),/Injected open failure/);
  await page.evaluate(()=>{window.qa.fail='';window.qa.cancel='open';});
  await page.locator('.meeting-list .open').click();
  await page.getByRole('alert').waitFor({state:'hidden'});
  assert.equal(await page.getByRole('dialog').count(),1,'canceling a switch leaves the library open without a failure');
  await page.evaluate(()=>window.qa.cancel='');
  await page.getByRole('button',{name:'Rename',exact:true}).click();
  await page.getByRole('textbox',{name:'Meeting title',exact:true}).fill('Draft survives');
  await page.evaluate(()=>window.qa.fail='save');
  await page.keyboard.press('Enter');
  await page.getByRole('alert').waitFor();
  assert.equal(await page.getByRole('textbox',{name:'Meeting title',exact:true}).inputValue(),'Draft survives');
  await page.evaluate(()=>window.qa.fail='');
  await page.getByRole('button',{name:'Save title',exact:true}).click();
  await page.getByRole('textbox',{name:'Meeting title',exact:true}).waitFor({state:'hidden'});
  assert.equal(await page.evaluate(()=>window.qa.rows[0].title),'Draft survives');
  await page.getByRole('button',{name:'Rename',exact:true}).click();
  await page.getByRole('textbox',{name:'Meeting title',exact:true}).fill('Discarded');
  await page.keyboard.press('Escape');
  assert.equal(await page.evaluate(()=>window.qa.rows[0].title),'Draft survives');
  const query=page.getByRole('searchbox',{name:'Search meetings',exact:true});
  await query.fill('old');
  await page.waitForFunction(()=>document.querySelector('[role="status"]')?.textContent==='Searching…');
  // Ensure the old request has started, then replace it with a newer query.
  await page.waitForFunction(()=>window.qa.started.includes('old'));
  await query.fill('new');
  await page.waitForFunction(()=>window.qa.finished.includes('old')&&window.qa.finished.includes('new'));
  assert.equal(await page.getByRole('alert').count(),0,'stale search errors must not replace current results');
  await query.fill('slow-success');
  await page.waitForFunction(()=>window.qa.started.includes('slow-success'));
  await query.fill('fast-success');
  await page.waitForFunction(()=>window.qa.finished.includes('slow-success')&&window.qa.finished.includes('fast-success'));
  assert.deepEqual(await page.locator('.meeting-hits span').allTextContents(),['Newest search result'],'a late successful search must not overwrite the newer query results');
  await query.fill('');
  await page.evaluate(()=>window.qa.fail='boards');
  await page.getByRole('button',{name:'Continue on it',exact:true}).click();
  await page.getByRole('alert').waitFor();
  assert.equal(await page.getByRole('dialog').count(),1);
  assert.equal(await page.evaluate(()=>window.qa.calls.includes('continue')),false);
  await page.evaluate(()=>window.qa.fail='remove');
  await page.getByRole('button',{name:'Delete',exact:true}).click();
  await page.getByRole('button',{name:'Delete',exact:true}).click();
  await page.getByRole('alert').waitFor();
  assert.equal(await page.getByRole('button',{name:'Cancel',exact:true}).count(),1);
  assert.equal(await page.evaluate(()=>window.qa.rows.length),1);
  await page.evaluate(()=>window.qa.fail='');
  await page.getByRole('button',{name:'Delete',exact:true}).click();
  await page.getByText('No saved meetings yet.',{exact:false}).waitFor();
  assert.equal(await page.evaluate(()=>window.qa.rows.length),0);
  assert.deepEqual(errors,[]);
  return {loadRetry:true,openFailure:true,cancelWithoutFailure:true,renameDraft:true,escapeCancels:true,staleSearchIgnored:true,staleSuccessIgnored:true,continueFailure:true,deleteRetry:true};
};
