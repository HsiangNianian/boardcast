const assert = require('node:assert/strict');
const fs = require('node:fs/promises');

module.exports = async function checkContents(page, baseUrl, evidence = 'docs/ui-ux-audit-2026-11-03/evidence/implementation') {
  const errors = [], checks = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => { localStorage.setItem('boardcast.lang', 'en'); localStorage.setItem('boardcast.log', 'open'); localStorage.setItem('boardcast.mode', 'ink'); });
  await page.emulateMedia({reducedMotion: 'reduce'});
  await page.goto(baseUrl); await page.locator('.splash').waitFor({state:'hidden'});
  await page.evaluate(async () => {
    const node = (id,label,extra={}) => ({id,label,aliases:[],kind:'node',marks:[],ink:'ink',...extra});
    const graph = {nodes:[node('n1','First decision',{by:'Alice'}),node('n2','Follow-up',{parent:'n1',group:'g1',marks:['星标']}),node('n3','Imported excerpt',{kind:'region',text:'Exact original source text.',at:{x:3000,y:2000,w:300,h:120}})],edges:[{from:'n1',to:'n2',label:'leads to',ink:'ink',by:'Alice'}],groups:[{id:'g1',label:'Actions'}],nextNode:4,nextGroup:2};
    const rect = {id:'free-box',type:'rectangle',x:4400,y:3000,width:100,height:80,angle:0,strokeColor:'#ff00ff',backgroundColor:'#ff00ff',fillStyle:'solid',strokeWidth:2,strokeStyle:'solid',roughness:0,opacity:100,groupIds:[],frameId:null,roundness:null,index:null,seed:1,version:1,versionNonce:1,updated:0,isDeleted:false,boundElements:null,link:null,locked:false};
    const scene = {elements:[rect],generated:[],files:{}};
    const empty = {nodes:[],edges:[],groups:[],nextNode:1,nextGroup:1};
    const row={version:2,storageRevision:1,id:'qa-contents',title:'Contents review',titled:true,createdAt:1,updatedAt:2,graph,scene,history:[],lines:[{text:'First decision leads to Follow-up.',speaker:'Alice',page:0,ms:1}],summary:'An existing draft.',pages:[{graph,scene,steps:[]},{graph:empty,steps:[]}],page:0,steps:[]};
    const db=await new Promise((yes,no)=>{const r=indexedDB.open('boardcast-v2',1);r.onupgradeneeded=()=>{r.result.createObjectStore('meetings',{keyPath:'id'});r.result.createObjectStore('assets');};r.onsuccess=()=>yes(r.result);r.onerror=()=>no(r.error);});
    await new Promise((yes,no)=>{const tx=db.transaction('meetings','readwrite');tx.objectStore('meetings').put(row);tx.oncomplete=yes;tx.onerror=()=>no(tx.error);});db.close();localStorage.setItem('boardcast.meeting',row.id);
  });
  await page.reload(); await page.locator('.splash').waitFor({state:'hidden'});
  const tabs=page.locator('.sidebar-tabs');
  const contents=page.locator('#sidebar-contents-panel');
  const item = title => contents.locator('li').filter({has:page.locator('strong').filter({hasText:title})}).first();
  await tabs.getByRole('tab',{name:'Transcript',exact:true}).focus();
  await page.keyboard.press('ArrowRight');
  assert.equal(await tabs.getByRole('tab',{name:'Summary',exact:true}).getAttribute('aria-selected'),'true');
  assert.equal(await page.locator('#sidebar-summary-panel').isVisible(),true);
  await page.keyboard.press('End');
  assert.equal(await tabs.getByRole('tab',{name:'Contents',exact:true}).getAttribute('aria-selected'),'true');
  await contents.getByText('Under: First decision',{exact:true}).waitFor();
  await contents.getByText('Group: Actions',{exact:true}).waitFor();
  assert.equal(await item('Imported excerpt').getByRole('button',{name:'Delete',exact:true}).count(),0);
  await item('Imported excerpt').getByText('Original text',{exact:true}).click();
  await contents.getByText('Exact original source text.',{exact:true}).waitFor();
  checks.push('tabs support arrows/Home/End; semantic hierarchy, relations and immutable source text are available');
  await item('First decision').getByRole('button',{name:'Rename',exact:true}).first().click();
  await contents.getByRole('textbox',{name:'Name',exact:true}).fill('Renamed decision');
  await page.keyboard.press('Enter');
  await item('Renamed decision').waitFor();
  assert.equal(await page.evaluate(()=>document.activeElement.textContent),'Rename');
  await page.getByRole('button',{name:'Undo',exact:true}).click();
  await item('First decision').waitFor();
  await page.getByRole('button',{name:'Redo',exact:true}).click();
  await item('Renamed decision').getByRole('button',{name:'Find in transcript',exact:true}).first().click();
  assert.equal(await tabs.getByRole('tab',{name:'Transcript',exact:true}).getAttribute('aria-selected'),'true');
  await page.locator('.line.jump').waitFor();
  checks.push('rename and undo/redo use semantic history; source action returns to the matching transcript');
  await tabs.getByRole('tab',{name:'Contents',exact:true}).click();
  const free=contents.getByRole('region',{name:'Free objects'}).locator('li');
  await free.getByRole('button',{name:'Rename',exact:true}).click();
  await contents.getByRole('textbox',{name:'Name',exact:true}).fill('My free shape');
  await page.keyboard.press('Enter');
  await contents.getByText('My free shape',{exact:true}).waitFor();
  await free.getByRole('button',{name:'Delete',exact:true}).click();
  assert.equal(await contents.getByText('My free shape',{exact:true}).count(),0);
  await page.getByRole('button',{name:'Undo',exact:true}).click();
  await contents.getByText('My free shape',{exact:true}).waitFor();
  await page.locator('.save-state.saved').waitFor();
  await page.reload(); await page.locator('.splash').waitFor({state:'hidden'});
  await tabs.getByRole('tab',{name:'Contents',exact:true}).click();
  await contents.getByText('My free shape',{exact:true}).waitFor();
  checks.push('free-object names and deletion are persisted and undo restores the whole object');
  await page.getByRole('slider',{name:'Sidebar width'}).focus();
  await page.keyboard.press('End');
  await page.waitForFunction(()=>Math.round(document.querySelector('aside.log').getBoundingClientRect().width)===400);
  await contents.getByRole('combobox',{name:'Board page'}).selectOption('1');
  await contents.getByText('This page has no board content yet.',{exact:true}).waitFor();
  await contents.getByRole('combobox',{name:'Board page'}).selectOption('0');
  await page.setViewportSize({width:720,height:600});
  await item('Imported excerpt').getByRole('button',{name:'Locate',exact:true}).click();
  assert.equal(await page.locator('main').getAttribute('aria-hidden'),'false');
  await page.waitForFunction(()=>{const svg=document.querySelector('.ink > svg');if(!svg)return false;const b=svg.viewBox.baseVal;return 3150>=b.x&&3150<=b.x+b.width&&2060>=b.y&&2060<=b.y+b.height;});
  await page.getByRole('tab',{name:'Meeting details',exact:true}).click();
  await contents.getByRole('region',{name:'Free objects'}).getByRole('button',{name:'Locate',exact:true}).click();
  await page.waitForFunction(()=>{const b=document.querySelector('.ink > svg').viewBox.baseVal;return 4450>=b.x&&4450<=b.x+b.width&&3040>=b.y&&3040<=b.y+b.height;});
  await page.waitForFunction(()=>document.activeElement.id==='board-panel');
  checks.push('sidebar width and page selection work; compact locate shows and centers distant source and free objects');
  await fs.mkdir(evidence,{recursive:true});
  await page.screenshot({path:`${evidence}/contents-locate-compact.png`});
  await page.getByRole('tab',{name:'Meeting details',exact:true}).click();
  await page.screenshot({path:`${evidence}/contents-list-compact.png`});
  assert.deepEqual(errors,[]);
  await fs.writeFile(`${evidence}/contents-check.json`,JSON.stringify({passed:true,checks,pageErrors:errors},null,2));
};
