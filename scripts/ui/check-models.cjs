const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
module.exports = async function checkModels(page, baseUrl, evidence = 'docs/ui-ux-audit-2026-11-03/evidence/implementation') {
  const report = {checks: [], pageErrors: []};
  const check = (condition, label) => {assert.ok(condition, label); report.checks.push(label);};
  await page.addInitScript(() => {
    localStorage.setItem('boardcast.lang', 'en');
    const qa = window.qa = {calls: [], fail: 'list', hold: '', listeners: {}, callbacks: {}, next: 0};
    qa.emit = (event, payload) => (qa.listeners[event] || []).forEach(id => qa.callbacks[id]?.({event, payload}));
    window.__TAURI_EVENT_PLUGIN_INTERNALS__ = {unregisterListener: (event, id) => qa.listeners[event] = (qa.listeners[event] || []).filter(x => x !== id)};
    window.__TAURI_INTERNALS__ = {transformCallback: callback => {qa.callbacks[++qa.next] = callback; return qa.next;}, unregisterCallback: id => delete qa.callbacks[id], invoke: async (command, args = {}) => {
      if (command === 'plugin:event|listen') {(qa.listeners[args.event] ||= []).push(args.handler); if (qa.holdListen && args.event === 'model-progress') await new Promise(resolve => qa.releaseListen = resolve); return args.handler;}
      return null;
    }};
  });
  page.on('pageerror', error => report.pageErrors.push(error.message));
  const open = () => page.getByRole('button', {name: 'Open models', exact: true}).click();
  const panel = page.getByRole('dialog', {name: 'Local models', exact: true});
  const item = name => panel.locator('.model').filter({has: page.locator('b', {hasText: new RegExp(`^${name}$`)})});
  const confirm = page.getByRole('dialog', {name: 'Delete Board model?', exact: true});
  try {
    await page.goto(`${baseUrl}/scripts/ui/fixtures/models.html`); await open();
    await panel.getByRole('alert').filter({hasText: 'Injected list failure'}).waitFor();
    await page.evaluate(() => window.qa.fail = '');
    await panel.getByRole('button', {name: 'Reload models', exact: true}).click();
    await item('Board model').waitFor();
    check(await panel.locator('.model-group').count() === 3, 'list failure can be retried; models are grouped by transcription, board and image use');
    check(await item('Board model').locator('details').getAttribute('open') === null && (await item('Vision add-on').innerText()).includes('Paired with Board model'), 'technical details stay collapsed and the image-model dependency is visible');
    await item('Board model').getByRole('button', {name: 'Delete', exact: true}).click();
    await confirm.getByText(/installed vision add-on stays/).waitFor();
    await confirm.getByRole('button', {name: 'Cancel', exact: true}).click();
    check(!await page.evaluate(() => window.qa.calls.includes('remove')), 'deletion explains dependent components and cancel does not remove files');
    await item('Board model').getByRole('button', {name: 'Delete', exact: true}).click();
    await page.evaluate(() => window.qa.fail = 'save');
    await confirm.getByRole('button', {name: 'Stop, save and delete', exact: true}).click();
    await confirm.getByRole('alert').filter({hasText: 'Injected save failure'}).waitFor();
    check(!await page.evaluate(() => window.qa.calls.includes('remove')), 'a failed meeting-save barrier prevents deletion and retains the confirmation');
    await page.evaluate(() => {window.qa.fail = ''; window.qa.hold = 'save'; window.qa.calls = [];});
    await confirm.getByRole('button', {name: 'Stop, save and delete', exact: true}).click();
    await confirm.getByRole('button', {name: 'Stop, save and delete', exact: true}).evaluate(button => button.click());
    await page.keyboard.press('Escape');
    check(await confirm.isVisible() && await page.evaluate(() => window.qa.calls.filter(call => call === 'save').length) === 1, 'pending deletion refuses duplicate submission and premature dismissal');
    await page.evaluate(() => {window.qa.hold = ''; window.qa.release();});
    await confirm.waitFor({state: 'hidden'});
    check(await page.evaluate(() => window.qa.calls.indexOf('save') < window.qa.calls.indexOf('remove')), 'deletion executes only after the save barrier completes');
    const speech = item('Speech recognition model');
    await speech.getByRole('button', {name: 'Delete', exact: true}).click();
    const speechConfirm = page.getByRole('dialog', {name: 'Delete Speech recognition model?', exact: true});
    await speechConfirm.getByText(/SenseVoice and Apple Auto need this pack/).waitFor();
    await speechConfirm.getByRole('button', {name: 'Cancel', exact: true}).click();
    check(true, 'speech deletion explains the SenseVoice, VAD, speaker and Apple Auto dependency');
    await page.evaluate(() => window.qa.fail = 'remove');
    await speech.getByRole('button', {name: 'Delete', exact: true}).click();
    await speechConfirm.getByRole('button', {name: 'Stop, save and delete', exact: true}).click();
    await speechConfirm.getByRole('alert').filter({hasText: 'Injected remove failure'}).waitFor();
    check(await speechConfirm.getByRole('button', {name: 'Stop, save and delete', exact: true}).isEnabled() && await page.evaluate(() => window.qa.catalog.models.find(m => m.id === 'voice').installed), 'removal failure before any file changes retains the installed model and allows retry');
    await page.evaluate(() => window.qa.fail = 'remove-partial');
    await speechConfirm.getByRole('button', {name: 'Stop, save and delete', exact: true}).click();
    await speechConfirm.getByRole('alert').filter({hasText: 'Injected partial remove failure'}).waitFor();
    const pendingSpeech = page.locator('.model-panel .model').filter({has: page.locator('b', {hasText: /^Speech recognition model$/})});
    await pendingSpeech.getByRole('button', {name: /^Resume download/, includeHidden: true}).waitFor({timeout: 3000});
    check(await pendingSpeech.getByText('Ready', {exact: true}).count() === 0, 'partial deletion failure refreshes the catalog while retaining the error and confirmation');
    await page.evaluate(() => window.qa.fail = '');
    await speechConfirm.getByRole('button', {name: 'Stop, save and delete', exact: true}).click();
    await speechConfirm.waitFor({state: 'hidden'});
    check(await speech.getByRole('button', {name: 'Download', exact: true}).isEnabled(), 'retry removes the remaining files and offers a fresh download');
    await page.evaluate(() => window.qa.fail = 'select');
    await item('Other board model').getByRole('button', {name: 'Use this', exact: true}).click();
    await panel.getByRole('alert').filter({hasText: 'Injected select failure'}).waitFor();
    await page.evaluate(() => window.qa.fail = '');
    await item('Other board model').getByRole('button', {name: 'Use this', exact: true}).click();
    await item('Other board model').getByText('In use', {exact: true}).waitFor();
    check(true, 'failed model selection remains retryable and only successful selection changes the badge');
    const downloading = item('Download model');
    await downloading.getByRole('button', {name: /^Resume download/}).click();
    await downloading.getByRole('button', {name: 'Pause', exact: true}).waitFor();
    await page.evaluate(() => window.qa.emit('model-progress', {id: 'download', state: 'downloading', downloaded: 5e8, total: 0, speed: 0}));
    await downloading.getByText(/total size is unknown/).waitFor();
    check(await downloading.getByRole('progressbar').getAttribute('value') === null && !/NaN|Infinity|%/.test(await downloading.innerText()), 'unknown download totals use indeterminate progress without invented percentages or ETA');
    await page.evaluate(() => window.qa.emit('model-progress', {id: 'download', state: 'verifying', downloaded: 2e9, total: 2e9, speed: 0}));
    await downloading.getByText('Verifying…', {exact: true}).waitFor();
    check(await downloading.getByRole('button', {name: 'Pause', exact: true}).isEnabled(), 'verification is shown as a distinct phase with cancellation still available');
    await downloading.getByRole('button', {name: 'Pause', exact: true}).click();
    await downloading.getByRole('button', {name: /^Resume download/}).waitFor();
    check(await downloading.getByText('Paused; downloaded files are kept.', {exact: true}).count() === 1, 'pause preserves the partial download and offers resume');
    await downloading.getByRole('button', {name: /^Resume download/}).click();
    await downloading.getByRole('button', {name: 'Pause', exact: true}).waitFor();
    await panel.getByRole('button', {name: 'Close', exact: true}).click();
    await page.waitForFunction(() => window.qa.listeners['model-progress'].length === 0); await open();
    await item('Download model').getByRole('button', {name: 'Pause', exact: true}).waitFor();
    await page.waitForFunction(() => window.qa.listeners['model-progress'].length === 1);
    check(await page.evaluate(() => window.qa.listeners['model-progress'].length) === 1, 'closing keeps the background download and reopening restores one progress subscription');
    await item('Download model').getByRole('button', {name: 'Pause', exact: true}).click();
    await page.setViewportSize({width: 720, height: 480});
    await item('Vision add-on').getByRole('button', {name: 'Delete', exact: true}).click();
    const visionConfirm = page.getByRole('dialog', {name: 'Delete Vision add-on?', exact: true});
    await visionConfirm.getByRole('button', {name: 'Cancel', exact: true}).scrollIntoViewIfNeeded();
    const rect = await visionConfirm.getByRole('button', {name: 'Cancel', exact: true}).boundingBox();
    check(rect && rect.y >= 0 && rect.y + rect.height <= 480, 'delete confirmation remains operable in a short window');
    await fs.mkdir(evidence, {recursive: true}); await page.screenshot({path: `${evidence}/model-delete-confirmation.png`});
    await visionConfirm.getByRole('button', {name: 'Cancel', exact: true}).click();
    await panel.getByRole('button', {name: 'Close', exact: true}).click();
    await page.waitForFunction(() => window.qa.listeners['model-progress'].length === 0);
    await page.evaluate(() => {window.qa.holdListen = true; window.qa.catalog.freeBytes = 0;});
    await open(); await page.waitForFunction(() => typeof window.qa.releaseListen === 'function');
    await item('Download model').getByText(/more disk space/).waitFor();
    check(await item('Download model').getByRole('button', {name: /^Resume download/}).isDisabled(), 'known insufficient disk space explains and disables download');
    await panel.getByRole('button', {name: 'Close', exact: true}).click();
    await page.evaluate(() => window.qa.releaseListen());
    await page.waitForFunction(() => window.qa.listeners['model-progress'].length === 0);
    check(true, 'a progress subscription that resolves after closing is immediately released');
    check(report.pageErrors.length === 0, 'model-management flow has no browser script errors'); report.passed = true;
  } catch (error) { report.error = String(error); throw error; }
  finally { await fs.mkdir(evidence, {recursive: true}); await fs.writeFile(`${evidence}/models-check.json`, JSON.stringify(report, null, 2) + '\n'); }
};
