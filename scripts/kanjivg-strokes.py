"""uv run scripts/kanjivg-strokes.py [kanjivg.tar.gz]

Convert kana and kanji absent from hanzi-writer-data to ordered centerlines.
Generated data is committed;
normal builds and offline playback need neither Python nor a download.
"""
import hashlib
import gzip
import io
import json
import math
import re
import sys
import tarfile
import urllib.request
import unicodedata
import xml.etree.ElementTree as ET
from pathlib import Path

from fontTools.pens.recordingPen import RecordingPen
from fontTools.svgLib.path import parse_path

ROOT = Path(__file__).resolve().parents[1]
REV = "70a0b7ae0c18ceb5cb358274b029cce0234a43bc"
SHA256 = "6131533e905365c1c0b0aa763eb24c53483e12874e15b654c94f07b7bfd36365"
URL = f"https://codeload.github.com/KanjiVG/kanjivg/tar.gz/{REV}"


def centerline(d):
    pen = RecordingPen()
    parse_path(d, pen)
    points = []
    for op, args in pen.value:
        if op == "moveTo":
            assert not points, "Each SVG path must be one stroke"
            points.append(args[0])
        elif op == "lineTo":
            points.append(args[0])
        elif op == "curveTo":
            p0, p1, p2, p3 = points[-1], *args
            steps = max(2, math.ceil(sum(math.dist(a, b) for a, b in zip((p0, p1, p2), (p1, p2, p3))) / 3))
            for i in range(1, steps + 1):
                t = i / steps
                points.append(tuple((1-t)**3*p0[k] + 3*(1-t)**2*t*p1[k] + 3*(1-t)*t*t*p2[k] + t**3*p3[k] for k in (0, 1)))
        elif op == "closePath":
            points.append(points[0])
        else:
            assert op == "endPath", f"Unsupported SVG operation: {op}"
    assert len(points) >= 2 and all(math.isfinite(v) for p in points for v in p)
    return [[round(x / 109, 4), round(y / 109, 4)] for x, y in points]


archive = Path(sys.argv[1]).read_bytes() if len(sys.argv) > 1 else urllib.request.urlopen(URL, timeout=60).read()
assert hashlib.sha256(archive).hexdigest() == SHA256, "Unexpected KanjiVG archive"
glyphs, kanji = {}, {}
with tarfile.open(fileobj=io.BytesIO(archive)) as tar:
    prefix = f"kanjivg-{REV}/"
    names = set(tar.getnames())
    for path in sorted(names):
        name = path.removeprefix(prefix + 'kanji/')
        if not re.fullmatch(r"[0-9a-f]{5,6}\.svg", name):
            continue
        code = int(name[:-4], 16)
        ch = chr(code)
        is_kana = 0x3041 <= code <= 0x30FE
        is_missing_kanji = unicodedata.name(ch, '').startswith('CJK ') and not (ROOT / 'node_modules/hanzi-writer-data' / f'{ch}.json').exists()
        if not (is_kana or is_missing_kanji):
            continue
        svg = ET.fromstring(tar.extractfile(path).read())
        assert svg.attrib["viewBox"] == "0 0 109 109"
        assert not any("transform" in e.attrib for e in svg.iter() if e.tag.endswith(("}g", "}path")))
        strokes = [centerline(p.attrib["d"]) for p in svg.iter("{http://www.w3.org/2000/svg}path")]
        assert strokes, chr(code)
        if is_kana:
            glyphs[ch] = {"strokes": strokes, "advance": 1}
        else:
            # Match hanzi-writer's coordinate system so loading and offline export stay shared.
            kanji[ch] = [[[round(x * 1024, 2), round(900 - y * 1024, 2)] for x, y in s] for s in strokes]
    license_text = tar.extractfile(prefix + "COPYING").read().decode()

assert len(glyphs) == 184
assert all(chr(c) in glyphs for a, b in [(0x3041, 0x3096), (0x30A1, 0x30FA)] for c in range(a, b + 1))
assert len(glyphs["デ"]["strokes"]) == 5
assert all(c in kanji for c in '働込峠辻気広渋沢栄実発桜駅図')
(ROOT / "src/ink/kana.json").write_text(json.dumps(glyphs, ensure_ascii=False, separators=(",", ":")) + "\n")
(ROOT / "src/ink/kanji.json.gz").write_bytes(gzip.compress(json.dumps(kanji, ensure_ascii=False, separators=(",", ":")).encode(), mtime=0))
