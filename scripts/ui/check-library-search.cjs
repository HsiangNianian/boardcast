const assert = require('node:assert/strict');
const fs = require('node:fs/promises');

module.exports = async function checkLibrarySearch(page, baseUrl, evidence) {
  await fs.mkdir(evidence, {recursive: true});
  const report = {checks: [], pageErrors: [], observations: {}};
  const check = (ok, name) => {report.checks.push({name, ok: !!ok}); console.log(`${ok ? 'PASS' : 'FAIL'}: ${name}`);};
  page.on('pageerror', error => report.pageErrors.push(error.message));
  await page.emulateMedia({reducedMotion: 'reduce'});
  await page.addInitScript(() => {
    for (const [key, value] of Object.entries({lang: 'en', theme: 'light', mode: 'ink', log: 'open', 'mode-hint': 'dismissed'})) localStorage.setItem('boardcast.' + key, value);
  });
  const read = () => page.evaluate(async () => {
    const db = await new Promise((yes, no) => {const r = indexedDB.open('boardcast-v2'); r.onsuccess = () => yes(r.result); r.onerror = () => no(r.error);});
    const rows = await new Promise((yes, no) => {const r = db.transaction('meetings').objectStore('meetings').getAll(); r.onsuccess = () => yes(r.result); r.onerror = () => no(r.error);});
    db.close(); return rows;
  });
  const library = page.getByRole('dialog', {name: 'Meetings', exact: true});
  const query = library.getByRole('searchbox', {name: 'Search meetings', exact: true});
  const rows = library.locator('.meeting-list > li');
  const archive = rows.filter({has: page.locator('.title', {hasText: '缓存 Cache design'})});
  const settled = () => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  const open = async () => {await page.locator('.meeting-library').click(); await query.waitFor(); await settled(); await library.getByText('Searching…', {exact: true}).waitFor({state: 'hidden'});};
  const close = () => library.getByRole('button', {name: 'Close', exact: true}).click();
  const search = async text => {
    await query.fill(text);
    await settled();
    await library.getByText('Searching…', {exact: true}).waitFor({state: 'hidden'});
  };
  const hit = text => archive.locator('.meeting-hits button').filter({hasText: text});
  const boardFocused = () => page.waitForFunction(() => document.activeElement?.id === 'board-panel', null, {timeout: 1500}).then(() => true, () => false);
  const currentBoard = () => page.locator('.pages [aria-current="page"]').getAttribute('aria-label');
  const lineVisible = text => page.locator('.line.jump').filter({hasText: text}).evaluate(element => {
    let scroller = element.parentElement;
    while (scroller.parentElement && !(/auto|scroll/.test(getComputedStyle(scroller).overflowY) && scroller.clientHeight < scroller.scrollHeight)) scroller = scroller.parentElement;
    const a = element.querySelector('.body > p').getBoundingClientRect(), b = scroller.getBoundingClientRect();
    return a.height > 0 && a.top >= b.top - 1 && a.bottom <= b.bottom + 1;
  });
  try {
    await page.goto(baseUrl); await page.locator('.splash').waitFor({state: 'hidden'});
    await page.evaluate(async () => {
      const board = label => {
        const graph = {nodes: [{id: 'n1', kind: 'node', label, aliases: [], marks: [], ink: 'ink'}], edges: [], groups: [], nextNode: 2, nextGroup: 1};
        return {graph, steps: [{t: 1, line: 1, d: {nodes: {set: graph.nodes}, nextNode: 2}}]};
      };
      const make = (id, title, pages, extra = {}) => ({version: 2, storageRevision: 1, id, title, titled: true, createdAt: 1, updatedAt: 2, history: [], lines: [], graph: pages[0].graph, steps: pages[0].steps, pages, page: 0, ...extra});
      const pages = [board('FirstBoardNeedle 首页'), board('SecondBoardNeedle 跨页目标')];
      const lines = Array.from({length: 60}, (_, i) => ({id: `search-line-${i}`, text: `Recorded detail ${i}`, speaker: 'A', ms: 1, page: 1}));
      lines[3] = {id: 'legacy', text: 'LegacyNeedle 原始记录', speaker: 'A', ms: 1};
      lines[40] = {id: 'explicit', text: 'TranscriptNeedle 第二板记录', speaker: 'A', ms: 1, page: 1};
      lines.push({id: 'manual', text: 'ManualNeedle UI action', manual: true, ms: 0, page: 1});
      const rows = [make('qa-search-current', 'Current agenda', [board('Current board')]), make('qa-search-archive', '缓存 Cache design', pages, {graph: pages[1].graph, steps: pages[1].steps, page: 1, lines, summary: 'SummaryNeedle 会议决定'}), make('qa-search-decoy', 'Cache old notes', [board('Other material')])];
      const db = await new Promise((yes, no) => {const r = indexedDB.open('boardcast-v2', 1); r.onupgradeneeded = () => {r.result.createObjectStore('meetings', {keyPath: 'id'}); r.result.createObjectStore('assets');}; r.onsuccess = () => yes(r.result); r.onerror = () => no(r.error);});
      await new Promise((yes, no) => {const tx = db.transaction('meetings', 'readwrite'); for (const row of rows) tx.objectStore('meetings').put(row); tx.oncomplete = yes; tx.onerror = () => no(tx.error);});
      db.close(); localStorage.setItem('boardcast.meeting', rows[0].id);
    });
    const before = await read(); await fs.writeFile(evidence + '/meetings-before.json', JSON.stringify(before, null, 2));
    await page.reload(); await page.locator('.splash').waitFor({state: 'hidden'});
    await open(); await search('Cache');
    check(await rows.count() === 2, 'a case-insensitive English term finds both matching meetings');
    await search('CACHE cache');
    check(await rows.count() === 2, 'repeated English terms retain the same matching meetings');
    await search('缓存 缓存');
    check(await archive.count() === 1 && await rows.count() === 1, 'repeated Chinese terms retain the matching meeting');
    await search('cache ca he');
    report.observations.overlap = await archive.locator('.meeting-hits button span').first().textContent();
    check(report.observations.overlap === '缓存 Cache design', 'overlapping highlights do not duplicate text in the visible result');
    await page.screenshot({path: evidence + '/overlap.png'});
    await search('cache SummaryNeedle');
    check(await rows.count() === 1 && await hit('会议决定').count() === 1, 'different terms can match the title and summary of one meeting');
    await search('Cache MissingNeedle');
    check(await rows.count() === 0 && await library.getByText('Nothing found.', {exact: true}).count() === 1, 'a missing required term gives the explicit no-results state');
    await search('ManualNeedle');
    check(await rows.count() === 0, 'manual edit notices do not masquerade as spoken transcript hits');
    await search('SecondBoardNeedle'); await hit('跨页目标').click();
    await page.locator('.ink-toolbar').waitFor({state: 'visible'});
    await settled();
    check(await currentBoard() === 'Board 2' && await page.locator('.ink-toolbar').getByRole('button', {name: 'Rename', exact: true}).isVisible() && await boardFocused(), 'a cross-meeting board hit opens the correct page and focuses its selected node');
    await open(); await search('SummaryNeedle'); await hit('会议决定').click();
    await page.locator('#sidebar-summary-panel .md').getByText('SummaryNeedle 会议决定', {exact: true}).waitFor();
    check(await page.getByRole('tab', {name: 'Summary', exact: true}).getAttribute('aria-selected') === 'true', 'a summary hit opens the summary tab');
    await open(); await search('TranscriptNeedle'); await hit('第二板记录').click();
    await page.locator('.line.jump').filter({hasText: 'TranscriptNeedle'}).waitFor(); await page.waitForTimeout(100);
    check(await currentBoard() === 'Board 2' && await lineVisible('TranscriptNeedle'), 'an explicit-page transcript hit reveals the correct historical line and board');
    const repeatStart = Date.now();
    await page.locator('#sidebar-transcript-panel .lines').focus(); await page.keyboard.press('Home');
    await page.waitForTimeout(200);
    assert(!await lineVisible('TranscriptNeedle'), 'Home must move the transcript away from the search result');
    await open(); await hit('第二板记录').focus(); await page.keyboard.press('Enter');
    await page.locator('.line.jump').filter({hasText: 'TranscriptNeedle'}).waitFor(); await page.waitForTimeout(100);
    report.observations.repeatedHitMs = Date.now() - repeatStart;
    check(await lineVisible('TranscriptNeedle'), 'opening the same transcript hit again reveals it after scrolling away');
    await open(); await search('LegacyNeedle'); await hit('原始记录').click();
    await page.locator('.line.jump').filter({hasText: 'LegacyNeedle'}).waitFor(); await page.waitForTimeout(100);
    report.observations.legacyBoard = await currentBoard();
    check(report.observations.legacyBoard === 'Board 1' && await lineVisible('LegacyNeedle'), 'a legacy transcript hit returns to the first board even when the meeting was saved on the second');
    await page.screenshot({path: evidence + '/legacy-hit.png'});
    await open(); await search('CACHE cache'); await close(); await settled();
    check(await page.locator('.meeting-library').evaluate(element => element === document.activeElement), 'closing the library without selecting a result returns focus to its trigger');
    await open();
    check(await query.inputValue() === 'CACHE cache' && await rows.count() === 2, 'reopening the library preserves the query and matching results');
    await page.setViewportSize({width: 720, height: 480});
    await search('SummaryNeedle'); await hit('会议决定').focus(); await page.keyboard.press('Enter');
    await page.locator('#sidebar-summary-panel .md').waitFor({state: 'visible'});
    check(await page.locator('#sidebar-summary-panel .md').isVisible(), 'keyboard opening a summary result works in the compact layout');
    await open(); await search('SecondBoardNeedle'); await hit('跨页目标').focus(); await page.keyboard.press('Enter');
    await page.locator('.ink-toolbar').waitFor({state: 'visible'});
    await settled();
    check(await page.locator('#board-panel').isVisible() && await boardFocused(), 'compact board search switches out of details and focuses the selected canvas item');
    await open(); await search('LegacyNeedle'); await hit('原始记录').focus(); await page.keyboard.press('Enter');
    await page.locator('.line.jump').filter({hasText: 'LegacyNeedle'}).waitFor(); await page.waitForTimeout(100);
    report.observations.compactJump = await page.locator('.line.jump').evaluate(element => ({text: element.textContent, box: element.getBoundingClientRect().toJSON(), parent: element.parentElement.getBoundingClientRect().toJSON(), scroll: element.parentElement.scrollTop}));
    check(await page.locator('#sidebar-transcript-panel').isVisible() && await lineVisible('LegacyNeedle'), 'compact transcript search switches to details and reveals its historical line');
    await page.screenshot({path: evidence + '/compact-transcript.png'});
    const after = await read();
    check(JSON.stringify(after) === JSON.stringify(before), 'searching and following results leave every saved meeting unchanged');
    await fs.writeFile(evidence + '/meetings-after.json', JSON.stringify(after, null, 2));
    await page.reload(); await page.locator('.splash').waitFor({state: 'hidden'}); await open();
    check(await query.inputValue() === 'LegacyNeedle' && await hit('原始记录').count() === 1, 'cold browser reload preserves the search query and finds the archived transcript');
    check(report.pageErrors.length === 0, 'the complete search flow has no uncaught application errors');
    assert(report.checks.every(c => c.ok), report.checks.filter(c => !c.ok).map(c => c.name).join('\n'));
  } finally {
    await fs.writeFile(evidence + '/report.json', JSON.stringify(report, null, 2) + '\n');
  }
};
