const assert = require('node:assert/strict');
const fs = require('node:fs/promises');

module.exports = async function checkReview(page, baseUrl, evidence = 'docs/ui-ux-audit-2026-11-03/evidence/implementation') {
  const errors = [], checks = [], pending = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => { localStorage.setItem('boardcast.lang','en'); localStorage.setItem('boardcast.localLlm','http://127.0.0.1:19877'); localStorage.setItem('boardcast.log','open'); });
  await page.route('http://127.0.0.1:19877/**', async route => {
    if (route.request().method()==='POST') await new Promise(resolve => pending.push(async () => { await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({choices:[{message:{content:'N 「Finished review board」'}}]})}).catch(()=>{});resolve(); }));
    else await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({status:'ok',data:[{id:'review-fixture'}]})});
  });
  const read = () => page.evaluate(async()=>{
    const db=await new Promise((yes,no)=>{const r=indexedDB.open('boardcast-v2');r.onsuccess=()=>yes(r.result);r.onerror=()=>no(r.error);});
    const row=await new Promise((yes,no)=>{const r=db.transaction('meetings').objectStore('meetings').get(localStorage.getItem('boardcast.meeting'));r.onsuccess=()=>yes(r.result);r.onerror=()=>no(r.error);});db.close();return row;
  });
  const send = async text => { await page.getByRole('textbox',{name:'What was said',exact:true}).fill(text);await page.getByRole('button',{name:'Put on the board',exact:true}).click(); };
  const waitPending = async count => { for(let i=0;i<100&&pending.length<count;i++) await page.waitForTimeout(50);assert.ok(pending.length>=count); };
  await page.goto(baseUrl); await page.locator('.splash').waitFor({state:'hidden'});
  await send('Keep this unfinished thought in the transcript.'); await waitPending(1);
  await page.evaluate(()=>{window.qaPut=IDBObjectStore.prototype.put;IDBObjectStore.prototype.put=function(...args){if(this.name==='meetings')throw new DOMException('Injected review disk full','QuotaExceededError');return window.qaPut.apply(this,args);};});
  await page.getByRole('button',{name:'End and review',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'End and review',exact:true});
  await dialog.getByRole('button',{name:'Wait for the board and review',exact:true}).click();
  await dialog.getByText('Waiting for board generation…',{exact:true}).waitFor();
  assert.equal(await page.locator('.review-summary').count(),0);
  await dialog.getByRole('button',{name:'Keep unfinished items and review',exact:true}).click();
  await dialog.getByRole('alert').filter({hasText:'Injected review disk full'}).waitFor();
  assert.equal(await page.locator('.review-summary').count(),0);
  assert.equal(await dialog.getByRole('button',{name:'Export a copy',exact:true}).isEnabled(),true);
  checks.push('wait can explicitly preserve pending work; save failure keeps the dialog open with a recovery export');
  await page.evaluate(()=>{IDBObjectStore.prototype.put=window.qaPut;});
  await dialog.getByRole('button',{name:'End and review',exact:true}).click();
  await page.locator('.review-summary').waitFor();
  assert.equal(await dialog.count(),0);
  await page.locator('.review-summary').getByText('1 transcript line · 1 board · 1 unfinished item',{exact:true}).waitFor();
  let row=await read();assert.equal(row.lines.length,1);assert.equal(row.lines[0].boardFailure,'cancelled');assert.equal(row.graph.nodes.length,0);
  await pending[0]();
  await page.waitForTimeout(150);
  row=await read();assert.equal(row.graph.nodes.length,0);assert.equal(row.lines.length,1);
  checks.push('review begins only after saving; cancelled line remains retryable and a late model response cannot draw');
  await page.getByRole('button',{name:'Continue working',exact:true}).click();
  await send('Please finish this second idea before review.');await waitPending(2);
  await page.getByRole('button',{name:'End and review',exact:true}).click();
  await dialog.getByRole('button',{name:'Wait for the board and review',exact:true}).click();
  await dialog.getByText('Waiting for board generation…',{exact:true}).waitFor();
  await pending[1]();
  await page.locator('.review-summary').waitFor();
  row=await read();assert.equal(row.lines.length,2);assert.equal(row.graph.nodes[0]?.label,'Finished review board');assert.equal(row.lines.filter(l=>l.failed).length,1);assert.equal(row.lines.some(l=>l.ms===undefined),false);
  await page.locator('.sidebar-tabs').getByRole('tab',{name:'Transcript',exact:true}).click();
  assert.equal(await page.getByRole('button',{name:'Retry this line',exact:true}).count(),1);
  checks.push('waiting lets a completed model result settle and save; review keeps transcript recovery available');
  await send('Continue the meeting with a new thought.');await waitPending(3);
  assert.equal(await page.locator('.review-summary').count(),0);
  await pending[2]();await page.locator('.save-state.saved').waitFor();
  checks.push('new input returns from review to the working state');
  assert.deepEqual(errors,[]);
  await fs.mkdir(evidence,{recursive:true});await page.screenshot({path:`${evidence}/review-complete.png`});
  await fs.writeFile(`${evidence}/review-check.json`,JSON.stringify({passed:true,checks,pageErrors:errors},null,2));
};
